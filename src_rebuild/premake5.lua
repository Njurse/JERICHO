            "platform/Windows/main.ico" 
        }

        includedirs { 
            SDL2_DIR.."/include",
            OPENAL_DIR.."/include",
			JPEG_DIR.."/",
        }

        links { 
            "opengl32",
            "SDL2", 
            "OpenAL32",
        }

    filter {"system:Windows", "platforms:x86"}
        libdirs { 
            SDL2_DIR.."/lib/x86",
            OPENAL_DIR.."/libs/Win32",
        }

    filter {"system:Windows", "platforms:x64"}
        libdirs { 
            SDL2_DIR.."/lib/x64",
            OPENAL_DIR.."/libs/Win64",
        }

    filter "system:Windows"
        linkoptions {
			"/SAFESEH:NO", -- Image Has Safe Exception Handers: No. Because of openal-soft
			"/MAP", -- linker map: gen_exports turns it into exports.def
			"/DEF:..\\exports.def", -- export every game symbol so mod DLLs can link
        }
        
    filter "system:linux"
        includedirs {
            "/usr/include/SDL2"
        }

        links {
            "GL",
            "openal",
            "SDL2",
            "dl",
        }

        -- export every game symbol so dlopen'd mod .so files can link
        linkoptions {
            "-Wl,--export-dynamic",
        }

    filter "configurations:Debug"
		targetsuffix "_dbg"
        defines { 
            "DEBUG_OPTIONS",
            "COLLISION_DEBUG",
			"CUTSCENE_RECORDER"
         }
		 symbols "On"

	filter "configurations:Release"
        optimize "Speed"
        -- A release pre-includes only JERICHO_RELEASE_MODS: this define trims the
        -- generated registry (Game/C/JERICHO/gen/jer_registry.c) to the same set
        -- the link filter above uses. A dev build (no define) keeps them all.
        --
        -- JERICHO: this config defines DEBUG_OPTIONS too. It used to not, so a
        -- Release build silently lacked the engine's debug surface -- the Debug
        -- Options pause submenu and its handlers, the free-camera exemption, the
        -- -startpos override, the collision-debug draw, the ghost road plane and
        -- the frontend version stamp -- and it also lacked the boot options, until
        -- those were un-gated in main.c. Two builds that differ in what they can do
        -- behave differently, which is what "it works on dev but not on release"
        -- turned out to be. The module SET is still trimmed by the define above;
        -- the debug surface is not.
        --
        -- The one thing a release DOES keep out is the stock Debug Options pause
        -- submenu: pause.c guards that menu entry on
        -- (DEBUG_OPTIONS && !JERICHO_RELEASE_MODS), so players do not get a
        -- right-way-up / free-camera / collision-debug menu, while everything the
        -- flag enables elsewhere (and every boot option) is present.
        defines { "JERICHO_RELEASE_MODS", "DEBUG_OPTIONS" }
		
	filter "configurations:Release_dev"
		targetsuffix "_dev"
        defines { 
            "DEBUG_OPTIONS",
            "COLLISION_DEBUG",
			"CUTSCENE_RECORDER"
        }
        optimize "Speed"

    filter { "files:**.c", "files:**.C" }
        compileas "C++"

    -- JERICHO is a self-contained framework folder (MODS + CONFIG) that
    -- ships next to the exe, so the runtime finds it from the game's
    -- working directory (which the game resolves everything from, same as
    -- gDataFolder). The repo copy is the source of truth; this mirrors it
    -- into the build. Post-build commands run from the project dir
    -- (build/), so the repo root is two levels up.
    -- MODS is always mirrored; CONFIG is only seeded when missing, so
    -- runtime changes to modlist.ini / module settings survive rebuilds.
    filter { "system:Windows" }
        postbuildcommands {
            "xcopy /E /I /Y \"..\\..\\JERICHO\\MODS\" \"%{cfg.buildtarget.directory}JERICHO\\MODS\"",
            "if not exist \"%{cfg.buildtarget.directory}JERICHO\\CONFIG\" xcopy /E /I \"..\\..\\JERICHO\\CONFIG\" \"%{cfg.buildtarget.directory}JERICHO\\CONFIG\"",
            -- modlist.ini is the single source of truth for which modules run, but the
            -- seeded-once CONFIG copy above meant a repo-side edit to it never reached
            -- bin/ - which is how a module could sit 'enabled=0' there while the repo
            -- said 1. /D copies only when the repo's is newer, so those edits land while
            -- a toggle made at runtime in bin/ still survives a rebuild.
            "xcopy /Y /D \"..\\..\\JERICHO\\CONFIG\\modlist.ini\" \"%{cfg.buildtarget.directory}JERICHO\\CONFIG\\modlist.ini\"",
            "copy /Y \"..\\..\\JERICHO\\build_mods.bat\" \"%{cfg.buildtarget.directory}JERICHO\\build_mods.bat\"",
            "copy /Y \"..\\..\\JERICHO\\build_game.bat\" \"%{cfg.buildtarget.directory}JERICHO\\build_game.bat\"",
            -- The updater, at the build's ROOT next to the exe, so a locally built
            -- install carries exactly what a downloaded one does. The packaging step
            -- used to be the only thing that placed these, which meant bin/<cfg> - the
            -- tree people actually run from - never had an updater. Both spellings, as
            -- the packages carry both: whichever OS the folder is copied to, one fits.
            "copy /Y \"..\\..\\JERICHO\\MODS\\mp\\tools\\pack_lan\\update_jericho.bat\" \"%{cfg.buildtarget.directory}update_jericho.bat\"",
            "copy /Y \"..\\..\\JERICHO\\MODS\\mp\\tools\\pack_lan\\update_jericho.sh\" \"%{cfg.buildtarget.directory}update_jericho.sh\"",
            -- The MOD STORE's helper, same reasoning as the updater above: the store
            -- cannot install without it, and it only sat next to the exe because
            -- someone copied it by hand - so a clean build (and CI) produced a game
            -- whose Mod Repo screen could download nothing. Both spellings.
            "copy /Y \"..\\..\\JERICHO\\CORE\\modstore\\modstore.bat\" \"%{cfg.buildtarget.directory}modstore.bat\"",
            "copy /Y \"..\\..\\JERICHO\\CORE\\modstore\\modstore.sh\" \"%{cfg.buildtarget.directory}modstore.sh\"",
        }

    -- The TOOLS are deliberately NOT mirrored. They are source, not game data: the
    -- game loads the compiled mods and CONFIG/, never a shell script. Mirroring them
    -- put every tool in two places, so a tool run from bin/ was a snapshot that could
    -- silently drift from the repo until someone rebuilt - which is exactly how a
    -- stale copy gets run and blamed. One canonical location:
    -- JERICHO/MODS/<mod>/tools.
    --
    -- One explicit command per mod FOLDER, discovered on disk rather than taken from
    -- JERICHO_COMPILED_MODS: the xcopy is recursive, so it mirrors folders that are
    -- not compiled mods too (combatd2 is one), and those would otherwise keep their
    -- tools/ forever. No cmd wildcard or for-loop syntax to get wrong, and `rd` needs
    -- the `if exist` guard because on a first build there is nothing to remove yet.
    local jer_mirrored_mods = {}
    for _, JER_DIR in ipairs(os.matchdirs("../JERICHO/MODS/*")) do
        table.insert(jer_mirrored_mods, path.getname(JER_DIR))
    end

    -- Modules whose FOLDER is not mirrored into the build.
    --
    -- d1cars is fetched by the build now (the allow-list in .github/workflows/build.yml
    -- fetches PsyCross and the four public mod source repos: mp, carhacks, crumple and
    -- d1cars), but its folder still must not land in the build output: it carries
    -- Driver 1 car content (shapes as .obj/.json, textures, LEV/LCF level data) that
    -- must not ride along in a build output or in a package made from one. gaildrv2 is
    -- unpublished and is not fetched at all. The recursive xcopy above mirrors every
    -- folder on disk, so without this the WHOLE submodule lands in bin/<cfg>/JERICHO/MODS/.
    -- A shipped LAN zip was found carrying 58 d1cars/gaildrv2 entries for exactly this reason.
    --
    -- The folder is dropped and then restored with only mod.toml (see below), so the
    -- compiled-in module still reports its id, version and author; none of its data ships.
    local JER_MIRROR_EXCLUDE = { d1cars = true, gaildrv2 = true }

    filter { "system:Windows" }
        for _, JER_MOD in ipairs(jer_mirrored_mods) do
            local JER_DEST = "%{cfg.buildtarget.directory}JERICHO\\MODS\\" .. JER_MOD
            local JER_TOOLS = JER_DEST .. "\\tools"
            local JER_CMDS = {
                "if exist \"" .. JER_TOOLS .. "\" rd /S /Q \"" .. JER_TOOLS .. "\"",
                -- the mod's COMPILED OUTPUT gets the same treatment: each mod_<id>
                -- project now writes its .lib/.pdb and an obj/ tree into its own
                -- folder, and the recursive mirror above would copy all of it into
                -- bin/. None of that is game data, so it is dropped on the way in.
                -- A runtime addon's <id>.dll IS game data and is left alone.
                "if exist \"" .. JER_DEST .. "\\obj\" rd /S /Q \"" .. JER_DEST .. "\\obj\"",
                "if exist \"" .. JER_DEST .. "\\lib\" rd /S /Q \"" .. JER_DEST .. "\\lib\"",
                -- A mod sourced from its own repository carries a .git gitfile. It is
                -- neither source nor game data, and shipping it would leak a path into
                -- the parent checkout. rd handles a real directory (a mod cloned in
                -- place); del handles the gitfile.
                "if exist \"" .. JER_DEST .. "\\.git\\\" rd /S /Q \"" .. JER_DEST .. "\\.git\"",
                "if exist \"" .. JER_DEST .. "\\.git\" del /Q /F \"" .. JER_DEST .. "\\.git\"",
                -- by EXTENSION, not by name. The artefacts are mod_<id>.lib/.pdb/.idb
                -- for a compiled-in mod and <id>.pdb/.exp/.idb for a DLL addon, and
                -- matching those names one at a time is exactly how one gets left
                -- behind (the .idb was, until this was made exhaustive). A runtime
                -- addon's <id>.dll is game data and no rule here touches it.
                "if exist \"" .. JER_DEST .. "\\*.lib\" del /Q \"" .. JER_DEST .. "\\*.lib\"",
                "if exist \"" .. JER_DEST .. "\\*.pdb\" del /Q \"" .. JER_DEST .. "\\*.pdb\"",
                "if exist \"" .. JER_DEST .. "\\*.exp\" del /Q \"" .. JER_DEST .. "\\*.exp\"",
                "if exist \"" .. JER_DEST .. "\\*.idb\" del /Q \"" .. JER_DEST .. "\\*.idb\"",
            }

            -- and, for the private/not-built modules, the whole folder - see the note on
            -- JER_MIRROR_EXCLUDE. Last, so it also removes anything the rules above left.
            if JER_MIRROR_EXCLUDE[JER_MOD] then
                table.insert(JER_CMDS, "if exist \"" .. JER_DEST .. "\" rd /S /Q \"" .. JER_DEST .. "\"")

                -- ...but the MANIFEST comes back. The module is compiled into the exe,
                -- so the game lists it either way; without a mod.toml it could only report
                -- its folder name and "?" as its version, and the mod store had nothing to
                -- compare against a repo entry. mod.toml carries no Driver 1 content --
                -- the exclusion is about the data, not the manifest.
                table.insert(JER_CMDS, "if not exist \"" .. JER_DEST .. "\" mkdir \"" .. JER_DEST .. "\"")
                table.insert(JER_CMDS, "copy /Y \"..\\..\\JERICHO\\MODS\\" .. JER_MOD .. "\\mod.toml\" \"" .. JER_DEST .. "\\mod.toml\" > nul")
            end

            postbuildcommands(JER_CMDS)
        end

    -- NOTE the explicit '/' before JERICHO in every path below. On MSBuild
    -- %{cfg.buildtarget.directory} expands to $(TargetDir), which ENDS in a
    -- separator, so "$(TargetDir)JERICHO" is right there. The gmake generator
    -- expands it to a literal ../bin/<cfg> with NO trailing separator, so the same
    -- concatenation produced "../bin/ReleaseJERICHO/MODS" -- a directory nobody
    -- reads. That meant a Linux build mirrored the mods somewhere the game never
    -- looks (and the package step then tarred a JERICHO/ with no mods in it), while
    -- the build still reported success.
    filter { "system:linux" }
        postbuildcommands {
            "mkdir -p \"%{cfg.buildtarget.directory}/JERICHO/MODS\" && cp -R ../../JERICHO/MODS/. \"%{cfg.buildtarget.directory}/JERICHO/MODS/\"",
            "mkdir -p \"%{cfg.buildtarget.directory}/JERICHO/CONFIG\" && cp -Rn ../../JERICHO/CONFIG/. \"%{cfg.buildtarget.directory}/JERICHO/CONFIG/\"",
            -- as on Windows: let a repo-side modlist.ini edit reach bin/, but only when
            -- it is the newer file (cp -u), so a runtime toggle there still survives.
            "cp -u ../../JERICHO/CONFIG/modlist.ini \"%{cfg.buildtarget.directory}/JERICHO/CONFIG/modlist.ini\"",
            -- the updater at the build's root, next to the exe - see the Windows block.
            -- cp does not carry the executable bit reliably and this one is a script, so
            -- the chmod is not decoration: the file is meant to be run from here.
            "cp -f ../../JERICHO/MODS/mp/tools/pack_lan/update_jericho.sh \"%{cfg.buildtarget.directory}/update_jericho.sh\"",
            "cp -f ../../JERICHO/MODS/mp/tools/pack_lan/update_jericho.bat \"%{cfg.buildtarget.directory}/update_jericho.bat\"",
            "chmod +x \"%{cfg.buildtarget.directory}/update_jericho.sh\"",
            -- the mod store's helper, next to the exe too - see the Windows block
            "cp -f ../../JERICHO/CORE/modstore/modstore.sh \"%{cfg.buildtarget.directory}/modstore.sh\"",
            "cp -f ../../JERICHO/CORE/modstore/modstore.bat \"%{cfg.buildtarget.directory}/modstore.bat\"",
            "chmod +x \"%{cfg.buildtarget.directory}/modstore.sh\"",
        }

    -- the same removals as on Windows, after the copy above. A static library is
    -- <id>.a on this toolchain, so both spellings are cleared.
    filter { "system:linux" }
        for _, JER_MOD in ipairs(jer_mirrored_mods) do
            local JER_DEST = "%{cfg.buildtarget.directory}/JERICHO/MODS/" .. JER_MOD
            local JER_CMDS = {
                -- .git is the submodule's gitfile (or a full directory for an
                -- in-place clone), never part of a mod.
                "rm -rf \"" .. JER_DEST .. "/tools\" \"" .. JER_DEST .. "/obj\" \"" .. JER_DEST .. "/lib\" \"" .. JER_DEST .. "/.git\"",
                -- by extension, as on Windows: a static library is .a here and the rest
                -- are linker/debug output. A runtime addon's <id>.so is game data.
                "rm -f \"" .. JER_DEST .. "\"/*.a \"" .. JER_DEST .. "\"/*.lib \"" .. JER_DEST .. "\"/*.o \"" .. JER_DEST .. "\"/*.pdb \"" .. JER_DEST .. "\"/*.exp \"" .. JER_DEST .. "\"/*.idb",
            }

            -- the private/not-built modules come out of the mirror entirely - same reason
            -- as on Windows, see JER_MIRROR_EXCLUDE above - but their MANIFEST stays, so a
            -- compiled-in module can still report its name, version and author
            if JER_MIRROR_EXCLUDE[JER_MOD] then
                table.insert(JER_CMDS, "rm -rf \"" .. JER_DEST .. "\"")
                table.insert(JER_CMDS, "mkdir -p \"" .. JER_DEST .. "\"")
                table.insert(JER_CMDS, "cp -f \"../../JERICHO/MODS/" .. JER_MOD .. "/mod.toml\" \"" .. JER_DEST .. "/mod.toml\"")
            end

            postbuildcommands(JER_CMDS)
        end

    -- A RELEASE build's mirror carries only the pre-included modules, so the
    -- shipped JERICHO/MODS matches exactly what the release exe links: someone who
    -- downloads JERICHO sees only those mods, not every experimental one. A dev
    -- build keeps them all. Done as a second, Release-only pass over the same
    -- folder list so the shared commands above do not have to grow a condition, and
    -- it runs last, after the mirror copy.
    filter { "system:Windows", "configurations:Release" }
        for _, JER_MOD in ipairs(jer_mirrored_mods) do
            if not jericho_is_release_mod(JER_MOD) then
                postbuildcommands {
                    "if exist \"%{cfg.buildtarget.directory}JERICHO\\MODS\\" .. JER_MOD .. "\" rd /S /Q \"%{cfg.buildtarget.directory}JERICHO\\MODS\\" .. JER_MOD .. "\"",
                }
            end
        end
    filter {}

    filter { "system:linux", "configurations:Release" }
        for _, JER_MOD in ipairs(jer_mirrored_mods) do
            if not jericho_is_release_mod(JER_MOD) then
                postbuildcommands {
                    "rm -rf \"%{cfg.buildtarget.directory}/JERICHO/MODS/" .. JER_MOD .. "\"",
                }
            end
        end
    filter {}

    -- A RELEASE build ships WITHOUT a modlist: the mirror above copies the repo's
    -- CONFIG/modlist.ini into bin/, and a package built from that would replace the
    -- player's toggles on install. Delete it instead, so the release's behaviour
    -- comes from each module's own mod.toml default (baked into jer_registry.c).
    -- Release-only, so a dev tree keeps the repo's full modlist locally.
    filter { "system:Windows", "configurations:Release" }
        postbuildcommands {
            "if exist \"%{cfg.buildtarget.directory}JERICHO\\CONFIG\\modlist.ini\" del /Q \"%{cfg.buildtarget.directory}JERICHO\\CONFIG\\modlist.ini\"",
        }
    filter {}

    filter { "system:linux", "configurations:Release" }
        postbuildcommands {
            "rm -f \"%{cfg.buildtarget.directory}/JERICHO/CONFIG/modlist.ini\"",
        }
    filter {}
