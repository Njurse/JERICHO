// [D] [T]
void ClearMem(char* mem, int size)
{
	// 16 bit aligned clear
#ifndef PSX
	memset(mem, 0, size);
#else
	char* end;
	end = mem + size;

	while ((((u_int)mem & 3) != 0 && (mem < end))) {
		*mem = 0;
		mem = (char*)((int)mem + 1);
	}

	while (mem <= end + -0x10) {
		*(u_int*)mem = 0;
		((u_int*)mem)[1] = 0;
		((u_int*)mem)[2] = 0;
		((u_int*)mem)[3] = 0;
		mem = (char*)((u_int*)mem + 4);
	}

	while (mem <= end + -4) {
		*(u_int*)mem = 0;
		mem = (char*)((u_int*)mem + 1);
	}

	while (mem < end) {
		*mem = 0;
		mem = (char*)((int)mem + 1);
	}
#endif // !PSX
}

